            .kw_struct => "`struct`",
            .kw_switch => "`switch`",
            .kw_test => "`test`",
            .kw_true => "`true`",
            .kw_try => "`try`",
            .kw_var => "`var`",
            .kw_while => "`while`",
            else => null,
        };
    }

    pub fn isKeyword(kind: Kind) bool {
        return @intFromEnum(kind) >= @intFromEnum(Kind.kw_and) and @intFromEnum(kind) <= @intFromEnum(Kind.kw_while);
    }
};

pub const Token = struct {
    kind: Kind,
    start: u32,
    end: u32,

    pub fn text(token: Token, source: []const u8) []const u8 {
        return source[token.start..token.end];
    }
};

