            .shr => "`>>`",
            .equal => "`=`",
            .equal_equal => "`==`",
            .bang_equal => "`!=`",
            .less => "`<`",
            .less_equal => "`<=`",
            .greater => "`>`",
            .greater_equal => "`>=`",
            .plus_equal => "`+=`",
            .minus_equal => "`-=`",
            .star_equal => "`*=`",
            .slash_equal => "`/=`",
            .percent_equal => "`%=`",
            .plus_percent_equal => "`+%=`",
            .minus_percent_equal => "`-%=`",
            .star_percent_equal => "`*%=`",
            .ampersand_equal => "`&=`",
            .pipe_equal => "`|=`",
            .caret_equal => "`^=`",
            .shl_equal => "`<<=`",
            .shr_equal => "`>>=`",
            .fat_arrow => "`=>`",
            .kw_and => "`and`",
            .kw_await => "`await`",
            .kw_break => "`break`",
