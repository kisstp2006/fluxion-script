    pub fn describe(kind: Kind) []const u8 {
        return switch (kind) {
            .identifier => "a name",
            .builtin => "a builtin",
            .int => "an integer",
            .float => "a float",
            .char => "a character",
            .string, .multiline_string => "a string",
            .fstring => "an f-string",
            .eof => "the end of the file",
            .invalid => "something that is not part of the language",
            else => spelling(kind).?,
        };
    }

